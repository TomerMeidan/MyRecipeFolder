export const categoryKey = (c: RecipeCategory) => `cat_${c.replace(/ /g, '_')}` as StringKey;
export const schemeKey = (s: ColorSchemeType) => `scheme_${s}` as StringKey;
export const langKey = (code: string) => `lang_${code}` as StringKey;

/** Fills {name} placeholders. */
export function format(template: string, params?: Record<string, string | number>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}
